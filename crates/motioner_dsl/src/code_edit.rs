//! Byte-range code edits: apply, invert, compose and re-key (D-0036).
//!
//! A [`CodeEdit`] is the planner's output: an ordered set of non-overlapping
//! replacements on the program text. It is a pure value (no file system, no
//! editor state), so the editor, the CLI and tests can apply and verify the
//! same edit. Undo uses [`CodeEdit::invert`]; baking and re-keying share the
//! same offset arithmetic as D-0027.

use std::fmt;

use motioner_core::OverrideSet;

/// How a code edit reproduces the change.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Strategy {
    /// A private literal is replaced in place (D-0027 strategy 1).
    PrivateLiteral,
    /// A static value or key is written next to the node's last write.
    LocalAssignment,
    /// A guarded statement is inserted or extended inside the loop body.
    LoopGuard,
    /// A literal shared by every iteration is edited for every instance.
    LoopSharedValue,
    /// Several single-change edits combined into one bake write.
    Combined,
}

impl Strategy {
    /// Stable lower-case name used in reports, traces and CLI output.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::PrivateLiteral => "private-literal",
            Self::LocalAssignment => "local-assignment",
            Self::LoopGuard => "loop-guard",
            Self::LoopSharedValue => "loop-shared-value",
            Self::Combined => "combined",
        }
    }
}

/// One replacement on the program: bytes `start..end` become `text`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Replacement {
    /// First byte replaced.
    pub start: usize,
    /// One past the last byte replaced; equal to `start` for an insertion.
    pub end: usize,
    /// Text written in its place.
    pub text: String,
}

impl Replacement {
    /// A replacement of `start..end` with `text`.
    #[must_use]
    pub fn new(start: usize, end: usize, text: impl Into<String>) -> Self {
        Self {
            start,
            end,
            text: text.into(),
        }
    }

    /// An insertion before `offset`.
    #[must_use]
    pub fn insert(offset: usize, text: impl Into<String>) -> Self {
        Self::new(offset, offset, text)
    }

    fn len(&self) -> usize {
        self.end - self.start
    }
}

/// Why a code edit could not be built, applied, inverted or composed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CodeEditError {
    /// A code edit needs at least one replacement.
    Empty,
    /// A replacement range is outside the program or inverted.
    Bounds {
        /// First byte of the offending replacement.
        start: usize,
        /// One past its last byte.
        end: usize,
        /// Program length.
        len: usize,
    },
    /// A replacement boundary does not fall on a UTF-8 character boundary.
    NotCharBoundary {
        /// The offending byte offset.
        offset: usize,
    },
    /// Two replacements overlap.
    Overlap {
        /// Start of the earlier replacement.
        first: usize,
        /// Start of the later one.
        second: usize,
    },
    /// A composition would edit text that another replacement generated.
    NotComposable {
        /// Byte offset in the intermediate program.
        offset: usize,
    },
}

impl fmt::Display for CodeEditError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Empty => write!(f, "a code edit needs at least one replacement"),
            Self::Bounds { start, end, len } => {
                write!(
                    f,
                    "replacement {start}..{end} is outside a {len}-byte program"
                )
            }
            Self::NotCharBoundary { offset } => {
                write!(f, "offset {offset} is not a UTF-8 character boundary")
            }
            Self::Overlap { first, second } => {
                write!(f, "replacements at {first} and {second} overlap")
            }
            Self::NotComposable { offset } => {
                write!(
                    f,
                    "offset {offset} falls inside text generated by the first edit"
                )
            }
        }
    }
}

impl std::error::Error for CodeEditError {}

/// An ordered, non-overlapping set of byte replacements plus its rationale.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CodeEdit {
    replacements: Vec<Replacement>,
    summary: String,
    strategy: Strategy,
}

impl CodeEdit {
    /// Builds an edit, sorting replacements by start offset.
    ///
    /// # Errors
    ///
    /// [`CodeEditError::Empty`] for no replacements and
    /// [`CodeEditError::Overlap`] when two ranges overlap (touching ranges and
    /// insertions at the same offset are allowed).
    pub fn new(
        mut replacements: Vec<Replacement>,
        summary: impl Into<String>,
        strategy: Strategy,
    ) -> Result<Self, CodeEditError> {
        if replacements.is_empty() {
            return Err(CodeEditError::Empty);
        }
        replacements.sort_by_key(|replacement| (replacement.start, replacement.end));
        for pair in replacements.windows(2) {
            let (first, second) = (&pair[0], &pair[1]);
            if first.end > second.start {
                return Err(CodeEditError::Overlap {
                    first: first.start,
                    second: second.start,
                });
            }
        }
        Ok(Self {
            replacements,
            summary: summary.into(),
            strategy,
        })
    }

    /// The replacements in ascending order.
    #[must_use]
    pub fn replacements(&self) -> &[Replacement] {
        &self.replacements
    }

    /// Human-readable summary of what the edit does.
    #[must_use]
    pub fn summary(&self) -> &str {
        &self.summary
    }

    /// The strategy that produced the edit.
    #[must_use]
    pub const fn strategy(&self) -> Strategy {
        self.strategy
    }

    /// Applies the edit to `program`.
    ///
    /// # Errors
    ///
    /// [`CodeEditError::Bounds`] or [`CodeEditError::NotCharBoundary`] when a
    /// replacement does not fit the text.
    pub fn apply(&self, program: &str) -> Result<String, CodeEditError> {
        let mut out = String::with_capacity(program.len() + self.replacements.len() * 8);
        let mut cursor = 0;
        for replacement in &self.replacements {
            validate_range(program, replacement.start, replacement.end)?;
            if replacement.start < cursor {
                return Err(CodeEditError::Overlap {
                    first: cursor,
                    second: replacement.start,
                });
            }
            out.push_str(&program[cursor..replacement.start]);
            out.push_str(&replacement.text);
            cursor = replacement.end;
        }
        out.push_str(&program[cursor..]);
        Ok(out)
    }

    /// The exact edit that undoes `self` on the program it produced.
    ///
    /// `before` is the program `self` was planned against; the inverse applies
    /// to the result of [`Self::apply`] and restores `before` byte for byte.
    ///
    /// # Errors
    ///
    /// Propagates bounds and UTF-8 errors from reading `before`.
    pub fn invert(&self, before: &str) -> Result<Self, CodeEditError> {
        let mut replacements = Vec::with_capacity(self.replacements.len());
        let mut delta = 0_isize;
        for replacement in &self.replacements {
            validate_range(before, replacement.start, replacement.end)?;
            let start = shift_signed(replacement.start, delta);
            let end = start + replacement.text.len();
            replacements.push(Replacement::new(
                start,
                end,
                &before[replacement.start..replacement.end],
            ));
            delta += replacement.text.len().cast_signed() - replacement.len().cast_signed();
        }
        Self::new(
            replacements,
            format!("undo: {}", self.summary),
            self.strategy,
        )
    }

    /// Composes `self` with `next`, where `next` applies to `self`'s result.
    ///
    /// # Errors
    ///
    /// [`CodeEditError::NotComposable`] when `next` edits text that `self`
    /// generated, which has no single equivalent on the original program.
    pub fn compose(&self, next: &Self) -> Result<Self, CodeEditError> {
        let mut replacements: Vec<Replacement> = self.replacements.clone();
        for replacement in &next.replacements {
            let start = map_offset(replacement.start, &self.replacements)?;
            let end = map_offset(replacement.end, &self.replacements)?;
            if end < start {
                return Err(CodeEditError::NotComposable {
                    offset: replacement.end,
                });
            }
            for existing in &self.replacements {
                let covered = start <= existing.start && existing.end <= end;
                let touches = start < existing.end && existing.start < end;
                if touches && !covered {
                    return Err(CodeEditError::NotComposable {
                        offset: replacement.start,
                    });
                }
            }
            replacements.retain(|existing| !(start <= existing.start && existing.end <= end));
            replacements.push(Replacement::new(start, end, replacement.text.clone()));
        }
        let strategy = if self.strategy == next.strategy {
            self.strategy
        } else {
            Strategy::Combined
        };
        Self::new(
            replacements,
            format!("{}; {}", self.summary, next.summary),
            strategy,
        )
    }

    /// Combines independent edits planned against the same program.
    ///
    /// # Errors
    ///
    /// [`CodeEditError::Overlap`] when two edits claim the same bytes.
    pub fn combine(edits: impl IntoIterator<Item = Self>) -> Result<Self, CodeEditError> {
        let mut replacements = Vec::new();
        let mut summary = Vec::new();
        for edit in edits {
            summary.push(edit.summary);
            for replacement in edit.replacements {
                if !replacements.contains(&replacement) {
                    replacements.push(replacement);
                }
            }
        }
        Self::new(replacements, summary.join("; "), Strategy::Combined)
    }

    /// The provenance key `id` has after this edit shifted its byte offsets.
    #[must_use]
    pub fn rekey_identity(&self, id: &str) -> String {
        if self.replacements.is_empty() {
            return id.to_owned();
        }
        let mut rest = id;
        let mut out = String::with_capacity(id.len());
        if let Some(after) = rest.strip_prefix('@') {
            let (digits, tail) = split_digits(after);
            let Ok(offset) = digits.parse::<usize>() else {
                return id.to_owned();
            };
            out.push('@');
            out.push_str(&shift_offset(offset, &self.replacements).to_string());
            rest = tail;
        }
        while !rest.is_empty() {
            if let Some(after) = rest.strip_prefix("/c") {
                let (digits, tail) = split_digits(after);
                let Ok(offset) = digits.parse::<usize>() else {
                    return id.to_owned();
                };
                out.push_str("/c");
                out.push_str(&shift_offset(offset, &self.replacements).to_string());
                rest = tail;
            } else if let Some(after) = rest.strip_prefix("/i") {
                let (digits, tail) = split_digits(after);
                out.push_str("/i");
                out.push_str(digits);
                rest = tail;
            } else {
                // Not a provenance key (an explicit `.id()`); leave it alone.
                return id.to_owned();
            }
        }
        out
    }

    /// Re-keys every entry of `set` after this edit shifted the offsets.
    #[must_use]
    pub fn rekey_overrides(&self, set: &OverrideSet) -> OverrideSet {
        if self.replacements.is_empty() {
            return set.clone();
        }
        let mut out = OverrideSet::new();
        for entry in set.entries() {
            let mut entry = entry.clone();
            entry.id = self.rekey_identity(&entry.id);
            out.push(entry);
        }
        out
    }
}

fn validate_range(program: &str, start: usize, end: usize) -> Result<(), CodeEditError> {
    if end < start || end > program.len() {
        return Err(CodeEditError::Bounds {
            start,
            end,
            len: program.len(),
        });
    }
    if !program.is_char_boundary(start) {
        return Err(CodeEditError::NotCharBoundary { offset: start });
    }
    if !program.is_char_boundary(end) {
        return Err(CodeEditError::NotCharBoundary { offset: end });
    }
    Ok(())
}

/// Maps a position in the edited text back to the original text.
fn map_offset(position: usize, replacements: &[Replacement]) -> Result<usize, CodeEditError> {
    let mut delta = 0_isize;
    for replacement in replacements {
        let start = shift_signed(replacement.start, delta);
        let end = start + replacement.text.len();
        if position < start {
            return Ok(shift_unsigned(position, delta));
        }
        if position == start {
            return Ok(replacement.start);
        }
        if position == end {
            return Ok(replacement.end);
        }
        if position < end {
            return Err(CodeEditError::NotComposable { offset: position });
        }
        delta += replacement.text.len().cast_signed() - replacement.len().cast_signed();
    }
    Ok(shift_unsigned(position, delta))
}

fn shift_signed(offset: usize, delta: isize) -> usize {
    usize::try_from(offset.cast_signed().saturating_add(delta)).unwrap_or(0)
}

fn shift_unsigned(offset: usize, delta: isize) -> usize {
    shift_signed(offset, delta)
}

fn split_digits(text: &str) -> (&str, &str) {
    let digits = text
        .as_bytes()
        .iter()
        .take_while(|byte| byte.is_ascii_digit())
        .count();
    text.split_at(digits)
}

fn shift_offset(offset: usize, replacements: &[Replacement]) -> usize {
    let mut value = offset.cast_signed();
    for replacement in replacements {
        if replacement.end <= offset {
            value += replacement.text.len().cast_signed() - replacement.len().cast_signed();
        }
    }
    usize::try_from(value).unwrap_or(offset)
}

#[cfg(test)]
mod tests {
    use super::*;

    const BEFORE: &str = "comp(name=\"T\", duration=1.0)\nc = circle(40)\n";

    #[test]
    fn apply_and_invert_restore_the_original_bytes() {
        let at = BEFORE.find("40").unwrap();
        let edit = CodeEdit::new(
            vec![Replacement::new(at, at + 2, "80")],
            "radius 40 -> 80",
            Strategy::PrivateLiteral,
        )
        .unwrap();
        let after = edit.apply(BEFORE).unwrap();
        assert!(after.contains("circle(80)"));
        let inverse = edit.invert(BEFORE).unwrap();
        assert_eq!(inverse.apply(&after).unwrap(), BEFORE);
    }

    #[test]
    fn composition_rewrites_an_inserted_literal() {
        let at = BEFORE.find("40").unwrap();
        let first = CodeEdit::new(
            vec![Replacement::new(at, at + 2, "80")],
            "radius 40 -> 80",
            Strategy::PrivateLiteral,
        )
        .unwrap();
        let middle = first.apply(BEFORE).unwrap();
        let second = CodeEdit::new(
            vec![Replacement::new(at, at + 2, "120")],
            "radius 80 -> 120",
            Strategy::PrivateLiteral,
        )
        .unwrap();
        let composed = first.compose(&second).unwrap();
        assert_eq!(
            composed.apply(BEFORE).unwrap(),
            second.apply(&middle).unwrap()
        );
        assert!(composed.apply(BEFORE).unwrap().contains("circle(120)"));
    }

    #[test]
    fn composing_inside_generated_text_is_refused() {
        let at = BEFORE.find("40").unwrap();
        let first = CodeEdit::new(
            vec![Replacement::new(at, at + 2, "123456")],
            "grow",
            Strategy::PrivateLiteral,
        )
        .unwrap();
        // In the edited text, the second byte of "123456" sits inside it.
        let second = CodeEdit::new(
            vec![Replacement::new(at + 1, at + 2, "9")],
            "edit inside generated text",
            Strategy::PrivateLiteral,
        )
        .unwrap();
        assert_eq!(
            first.compose(&second),
            Err(CodeEditError::NotComposable { offset: at + 1 })
        );
    }

    #[test]
    fn overlapping_replacements_are_refused() {
        let error = CodeEdit::new(
            vec![Replacement::new(30, 34, "a"), Replacement::new(32, 36, "b")],
            "overlap",
            Strategy::PrivateLiteral,
        )
        .unwrap_err();
        assert!(matches!(error, CodeEditError::Overlap { .. }));
    }

    #[test]
    fn combining_independent_edits_keeps_both() {
        let at = BEFORE.find("40").unwrap();
        let a = CodeEdit::new(
            vec![Replacement::new(at, at + 2, "80")],
            "a",
            Strategy::PrivateLiteral,
        )
        .unwrap();
        let b = CodeEdit::new(
            vec![Replacement::new(0, 1, "C")],
            "b",
            Strategy::LocalAssignment,
        )
        .unwrap();
        let combined = CodeEdit::combine([a, b]).unwrap();
        let after = combined.apply(BEFORE).unwrap();
        assert!(after.starts_with("Comp"));
        assert!(after.contains("circle(80)"));
        assert_eq!(combined.strategy(), Strategy::Combined);
    }

    #[test]
    fn rekeying_shifts_provenance_offsets_and_keeps_iterations() {
        let edit = CodeEdit::new(
            vec![Replacement::new(0, 0, "1234")],
            "insert four bytes",
            Strategy::LocalAssignment,
        )
        .unwrap();
        assert_eq!(edit.rekey_identity("@10/i2"), "@14/i2");
        assert_eq!(edit.rekey_identity("@10/c20/i3"), "@14/c24/i3");
        assert_eq!(edit.rekey_identity("title"), "title");
    }
}
